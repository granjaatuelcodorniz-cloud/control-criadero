create table if not exists public.analysis_day_corrections (
  id bigint generated by default as identity primary key,
  date date not null unique,
  original_huevos_total integer,
  corrected_huevos_total integer not null check (corrected_huevos_total >= 0),
  corrected_docenas_total integer check (corrected_docenas_total >= 0),
  reason text,
  method text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.analysis_day_corrections enable row level security;

drop policy if exists "analysis_day_corrections_select_authenticated"
  on public.analysis_day_corrections;

create policy "analysis_day_corrections_select_authenticated"
  on public.analysis_day_corrections
  for select
  to authenticated
  using (true);

drop policy if exists "analysis_day_corrections_owner_write"
  on public.analysis_day_corrections;

create policy "analysis_day_corrections_owner_write"
  on public.analysis_day_corrections
  for all
  to authenticated
  using (
    exists (
      select 1
      from public.profiles
      where profiles.id = auth.uid()
        and profiles.role = 'owner'
    )
  )
  with check (
    exists (
      select 1
      from public.profiles
      where profiles.id = auth.uid()
        and profiles.role = 'owner'
    )
  );

